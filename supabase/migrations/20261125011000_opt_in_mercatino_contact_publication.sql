-- Explicit opt-in for publishing seller email/phone in public marketplace listings.
alter table public.mercatino
  add column if not exists contatto_pubblico_consenso boolean not null default false;

-- Preserve listings that were already publicly visible under the existing explicit form notice.
update public.mercatino
set contatto_pubblico_consenso = true
where pubblicato is true
  and (nullif(btrim(contatto),'') is not null or nullif(btrim(telefono),'') is not null)
  and contatto_pubblico_consenso is distinct from true;

create table if not exists private.mercatino_contact_consent_log (
  id bigint generated by default as identity primary key,
  mercatino_id bigint not null references public.mercatino(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  consented boolean not null,
  source text not null default 'mercatino-form',
  created_at timestamptz not null default now()
);

alter table private.mercatino_contact_consent_log enable row level security;
revoke all on table private.mercatino_contact_consent_log from public, anon, authenticated;

create or replace function private.log_mercatino_contact_consent()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor uuid := coalesce(auth.uid(), new.created_by);
begin
  if tg_op = 'INSERT' then
    if new.contatto_pubblico_consenso is true then
      insert into private.mercatino_contact_consent_log(mercatino_id,user_id,consented,source,created_at)
      values(new.id,v_actor,true,'mercatino-form',now());
    end if;
  elsif new.contatto_pubblico_consenso is distinct from old.contatto_pubblico_consenso then
    insert into private.mercatino_contact_consent_log(mercatino_id,user_id,consented,source,created_at)
    values(new.id,v_actor,new.contatto_pubblico_consenso,'mercatino-form',now());
  end if;
  return new;
end;
$function$;

revoke all on function private.log_mercatino_contact_consent() from public, anon, authenticated;

drop trigger if exists trg_log_mercatino_contact_consent on public.mercatino;
create trigger trg_log_mercatino_contact_consent
after insert or update of contatto_pubblico_consenso on public.mercatino
for each row execute function private.log_mercatino_contact_consent();

-- Record the already-public state as a legacy publication, not as a newly collected checkbox consent.
insert into private.mercatino_contact_consent_log(mercatino_id,user_id,consented,source,created_at)
select m.id,m.created_by,true,'legacy_public_listing',coalesce(m.updated_at,m.created_at)
from public.mercatino m
where m.pubblicato is true
  and m.contatto_pubblico_consenso is true
  and not exists (
    select 1 from private.mercatino_contact_consent_log l
    where l.mercatino_id=m.id
  );

create or replace function public.get_public_company_mercatino(p_slug text)
returns table(
  id bigint,titolo text,categoria text,categoria_label text,anteprima text,descrizione text,
  prezzo text,condizioni text,immagine text,contatto text,telefono text,nome_cognome text,created_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $function$
  select m.id,m.titolo,m.categoria,m.categoria_label,m.anteprima,m.descrizione,
         m.prezzo,m.condizioni,m.immagine,
         case when m.contatto_pubblico_consenso is true then m.contatto else null end,
         case when m.contatto_pubblico_consenso is true then m.telefono else null end,
         null::text,m.created_at
  from public.mercatino m
  join public.aziende a on a.id=m.azienda_id
  where a.stato='attiva'
    and lower(a.slug)=lower(trim(p_slug))
    and m.pubblicato is true
    and lower(coalesce(m.stato,''))='disponibile'
    and m.contatto_pubblico_consenso is true
    and (nullif(btrim(m.contatto),'') is not null or nullif(btrim(m.telefono),'') is not null)
  order by m.created_at desc;
$function$;

